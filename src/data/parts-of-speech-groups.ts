export const ALL_POS_GROUPS: POSGroup[] = POS_GROUPS_RAW;

/**
 * Get a group by ID
 */
export function getPOSGroup(id: string): POSGroup | undefined {
  return ALL_POS_GROUPS.find(g => g.id === id);
}

/**
 * Get all non-checkpoint groups
 */
export function getContentGroups(): POSGroup[] {
  return ALL_POS_GROUPS.filter(g => !g.isCheckpoint);
}

/**
 * Get groups that have been unlocked based on progress
 */
export function getUnlockedGroups(
  completedGroupIds: Set<string>,
   
  _threshold: number,
): POSGroup[] {
  return ALL_POS_GROUPS.filter(group => {
    if (!group.prerequisite) return true;
    return completedGroupIds.has(group.prerequisite);
  });
}

/**
 * Get the next group after a given group
 */
export function getNextGroup(currentGroupId: string): POSGroup | null {
  const index = ALL_POS_GROUPS.findIndex(g => g.id === currentGroupId);
  if (index === -1 || index === ALL_POS_GROUPS.length - 1) return null;
  return ALL_POS_GROUPS[index + 1];
}
